##########################################################
"""
Builds docker-compose.yml, one devcontainer per project, and the UI's calculators.json from projects.json.

projects.json is the only file you edit by hand. Add a project there, run
    python3 generate.py
and you get a new service in docker-compose.yml plus .devcontainer/<name>/devcontainer.json.

    python3 generate.py --check    exit 1 if the generated files are out of date (used in CI)
    python3 generate.py --services petro weather    compose services to start for those projects (used by make up)

Standard library only, so it runs on the host without installing anything.
"""
##########################################################
import os
import sys
import json
from os.path import dirname, abspath, join

ROOT = dirname(abspath(__file__))
REQUIRED = ['name', 'label', 'repo', 'git', 'package', 'cpus', 'memory']


##########################################################
def loadProjects(path=join(ROOT, 'projects.json')):
    """Read and check projects.json. Collects every problem and raises once."""
    ######################################################
    with open(path) as f:
        cfg = json.load(f)
    errors, names = [], set()
    for p in cfg.get('projects', []):
        missing = [k for k in REQUIRED if k not in p]
        if missing: errors.append(f"project {p.get('name', '?')} missing {missing}")
        name = p.get('name', '')
        if not name.replace('-', '').isalnum() or name.lower() != name: errors.append(f"project name {name!r} must be lowercase letters, numbers or dashes")
        if name in names: errors.append(f"duplicate project name {name!r}")
        names.add(name)
    if not cfg.get('projects'): errors.append("no projects listed")
    if errors: raise ValueError("projects.json check failed:\n  - " + "\n  - ".join(errors))
    return cfg


##########################################################
def composeText(cfg={}):
    """docker-compose.yml as text (built by hand so no PyYAML needed)."""
    ######################################################
    ws, root = cfg['workspace'], cfg['workspace']['projects_root']
    L = [
        "# GENERATED by generate.py from projects.json. Edit projects.json, not this file.",
        f"name: {ws['name']}",
        "",
        "services:",
        "",
        "  # Shared services ###################################################",
        "  mlflow:",
        "    build:",
        "      context: .",
        "      dockerfile: Dockerfile.mlflow",
        f"    container_name: {ws['name']}-mlflow",
        "    ports:",
        f"      - \"{ws['mlflow_port']}:5000\"",
        "    volumes:",
        "      - mlruns:/mlruns",
        "    restart: unless-stopped",
        "    healthcheck:",
        "      test: [\"CMD\", \"python\", \"-c\", \"import urllib.request; urllib.request.urlopen('http://localhost:5000')\"]",
        "      interval: 10s",
        "      timeout: 5s",
        "      retries: 10",
        "      start_period: 30s",
        "    networks:",
        "      - ml-network",
        "",
        "  postgres:",
        "    image: postgres:16-alpine",
        f"    container_name: {ws['name']}-postgres",
        "    environment:",
        f"      - POSTGRES_DB={ws['postgres_db']}",
        f"      - POSTGRES_USER={ws['postgres_user']}",
        f"      - POSTGRES_PASSWORD={ws['postgres_password']}",
        "    ports:",
        f"      - \"{ws['postgres_port']}:5432\"",
        "    volumes:",
        "      - pgdata:/var/lib/postgresql/data",
        "    restart: unless-stopped",
        "    healthcheck:",
        f"      test: [\"CMD-SHELL\", \"pg_isready -U {ws['postgres_user']} -d {ws['postgres_db']}\"]",
        "      interval: 10s",
        "      timeout: 5s",
        "      retries: 10",
        "      start_period: 20s",
        "    networks:",
        "      - ml-network",
    ]
    ######################################################
    for p in cfg['projects']:
        repo = f"{root}/{p['repo']}"
        env = {'MLFLOW_TRACKING_URI': 'http://mlflow:5000', **({'PYTHONPATH': f"/workspace/{p['package']}"} if p.get('set_pythonpath', True) else {}), **p.get('env', {})}
        deps = ['mlflow'] + (['postgres'] if p.get('uses_postgres') else [])
        def serviceBlock(svc, command=None, port=None, restart='"no"'):
            b = [
                f"  {svc}:",
                "    build:",
                f"      context: {repo}",
                "      dockerfile: Dockerfile",
                f"    container_name: {ws['name']}-{svc}",
            ]
            if command: b.append(f"    command: {command}")
            b += ["    volumes:", f"      - {repo}:/workspace"]
            if port: b += ["    ports:", f"      - \"{port[0]}:{port[1]}\""]
            b.append("    environment:")
            b += [f"      - {k}={v}" for k, v in env.items()]
            b.append("    depends_on:")
            for d in deps: b += [f"      {d}:", "        condition: service_healthy"]
            b += [
                "    deploy:",
                "      resources:",
                "        limits:",
                f"          cpus: \"{p['cpus']}\"",
                f"          memory: {p['memory']}",
                f"    restart: {restart}",
                "    networks:",
                "      - ml-network",
            ]
            return b
        L += ["", f"  # {p['label']} " + "#" * max(3, 66 - len(p['label']))]
        L += serviceBlock(p['name'])
        if p.get('api'):
            api = p['api']
            L += [""] + serviceBlock(f"{p['name']}-api", command=api['command'], port=(api.get('host_port', api['port']), api['port']), restart='unless-stopped')
    ######################################################
    ui = ws.get('ui')
    if ui:
        L += ["", "  # UI " + "#" * 63,
              "  ui:",
              "    image: node:20-slim",
              f"    container_name: {ws['name']}-ui",
              "    working_dir: /app",
              "    command: sh -c \"npm install --no-audit --no-fund && npm run dev\"",
              "    volumes:",
              f"      - {root}/{ui['repo']}:/app",
              "      - ./calculators.json:/config/calculators.json:ro",
              "      - ui_node_modules:/app/node_modules",
              "    environment:",
              "      - CALCULATORS_FILE=/config/calculators.json",
              "      - IN_DOCKER=1",
              "    ports:",
              f"      - \"{ui['port']}:5173\"",
              "    restart: unless-stopped",
              "    networks:",
              "      - ml-network"]
    L += ["", "volumes:", "  mlruns:", "  pgdata:"] + (["  ui_node_modules:"] if ui else []) + ["", "networks:", "  ml-network:", "    driver: bridge", ""]
    return "\n".join(L)


##########################################################
def devcontainerText(cfg={}, p={}):
    """One devcontainer per project, all pointing at the same compose stack."""
    ######################################################
    ws = cfg['workspace']
    run = [p['name'], 'mlflow'] + (['postgres'] if p.get('uses_postgres') else []) + ([f"{p['name']}-api"] if p.get('api') else []) + (['ui'] if ws.get('ui') else [])
    ports = {str(ws['mlflow_port']): 'MLflow UI (shared)'}
    for fp in p.get('forward_ports', []): ports[str(fp)] = 'Dev server'
    if p.get('api'): ports[str(p['api'].get('host_port', p['api']['port']))] = 'API'
    if ws.get('ui'): ports[str(ws['ui']['port'])] = 'ML Platform UI'
    dc = {
        "name": f"{p['label']} (workspace)",
        "dockerComposeFile": "../../docker-compose.yml",
        "service": p['name'],
        "runServices": run,
        "workspaceFolder": "/workspace",
        # Closing one window must not stop the containers the other windows are using
        "shutdownAction": "none",
        "customizations": {"vscode": {
            "extensions": ["ms-python.python", "ms-python.vscode-pylance"],
            "settings": {"python.defaultInterpreterPath": "/usr/local/bin/python",
                         "python.formatting.provider": "black", "editor.formatOnSave": True}}},
        "forwardPorts": [int(x) for x in p.get('forward_ports', [])],
        "portsAttributes": {k: {"label": v, "onAutoForward": "notify"} for k, v in ports.items()},
        "remoteUser": "root",
    }
    if p.get('post_create'): dc["postCreateCommand"] = p['post_create']
    return json.dumps(dc, indent=2) + "\n"


##########################################################
def registryText(cfg={}):
    """calculators.json for the UI: where each calculator API lives inside the network and from the host."""
    ######################################################
    ws = cfg['workspace']
    reg = {'mlflow_url': f"http://localhost:{ws['mlflow_port']}", 'calculators': []}
    for p in cfg['projects']:
        if not p.get('api'): continue
        api = p['api']
        reg['calculators'].append({'name': p['name'], 'label': p['label'],
                                   'internal_url': f"http://{p['name']}-api:{api['port']}",
                                   'host_url': f"http://localhost:{api.get('host_port', api['port'])}"})
    return json.dumps(reg, indent=2) + "\n"


##########################################################
def uiDevcontainerText(cfg={}):
    """Dev container for working on the UI itself inside the workspace."""
    ######################################################
    ws = cfg['workspace']
    dc = {
        "name": "ML-Platform-UI (workspace)",
        "dockerComposeFile": "../../docker-compose.yml",
        "service": "ui",
        "runServices": ["ui"],
        "workspaceFolder": "/app",
        "shutdownAction": "none",
        "customizations": {"vscode": {"extensions": ["dbaeumer.vscode-eslint", "esbenp.prettier-vscode"]}},
        "portsAttributes": {str(ws['ui']['port']): {"label": "ML Platform UI", "onAutoForward": "notify"}},
        "remoteUser": "root",
    }
    return json.dumps(dc, indent=2) + "\n"


##########################################################
def servicesFor(cfg={}, names=[]):
    """Compose services to start for the given project names: the project, its API, and the UI."""
    ######################################################
    if not names: return []
    known = {p['name']: p for p in cfg['projects']}
    unknown = [n for n in names if n not in known and n not in ('ui', 'mlflow', 'postgres') and not n.endswith('-api')]
    if unknown: raise ValueError(f"unknown project(s) {unknown}, pick from {list(known)}")
    services = []
    for n in names:
        services.append(n)
        if n in known and known[n].get('api'): services.append(f"{n}-api")
    if cfg['workspace'].get('ui'): services.append('ui')
    return list(dict.fromkeys(services))


##########################################################
def plannedFiles(cfg={}):
    files = {join(ROOT, 'docker-compose.yml'): composeText(cfg), join(ROOT, 'calculators.json'): registryText(cfg)}
    if cfg['workspace'].get('ui'):
        files[join(ROOT, '.devcontainer', 'ui', 'devcontainer.json')] = uiDevcontainerText(cfg)
    for p in cfg['projects']:
        files[join(ROOT, '.devcontainer', p['name'], 'devcontainer.json')] = devcontainerText(cfg, p)
    return files


##########################################################
def main():
    ######################################################
    cfg = loadProjects()
    if '--services' in sys.argv:
        print(' '.join(servicesFor(cfg, sys.argv[sys.argv.index('--services') + 1:])))
        return
    files = plannedFiles(cfg)
    check = '--check' in sys.argv
    stale = []
    for path, text in files.items():
        current = open(path).read() if os.path.exists(path) else None
        if current == text: continue
        stale.append(os.path.relpath(path, ROOT))
        if not check:
            os.makedirs(dirname(path), exist_ok=True)
            with open(path, 'w') as f: f.write(text)
    ######################################################
    # Devcontainer folders for projects that were removed from projects.json
    names = {p['name'] for p in cfg['projects']} | ({'ui'} if cfg['workspace'].get('ui') else set())
    dc_root = join(ROOT, '.devcontainer')
    orphans = [d for d in (os.listdir(dc_root) if os.path.isdir(dc_root) else []) if os.path.isdir(join(dc_root, d)) and d not in names]
    ######################################################
    if check:
        if stale:
            print("Out of date, run python3 generate.py:\n  " + "\n  ".join(stale)); sys.exit(1)
        print("Generated files are up to date")
    else:
        print("Updated:\n  " + "\n  ".join(stale) if stale else "Nothing to update")
    if orphans: print(f"Note: .devcontainer/{', .devcontainer/'.join(orphans)} no longer in projects.json, delete by hand")


##########################################################
if __name__ == "__main__":
    main()
